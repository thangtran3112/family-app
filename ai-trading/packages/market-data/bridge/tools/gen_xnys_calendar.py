"""Generate the bridge's embedded XNYS calendar, and the Python-truth drift golden.

Two artifacts, produced by deliberately different paths so the drift test can catch a divergence:

1. ``internal/xnys/xnys.json`` holds session *dates* and early-close *dates* only. The Go loader
   derives each open/close instant from the ET wall clock plus tzdata, so a wrong UTC offset (the
   5U failure mode) shows up as a test failure rather than a silent one-hour error.
2. ``testdata/calendar/xnys_python_golden.json`` holds the Desk calendar's own
   ``ai_trading.core.calendar.session("stock", day)`` instants for every day in the range, loaded
   straight from its source file (no package import, per 02u T2's sanctioned golden replay).

Regenerate **yearly** (02u §9 ruling 6, sync-checklist item) from a checkout whose
``packages/family-desk/backend`` is current, then commit both files plus the drift-test run:

    cd ai-trading/packages/market-data/bridge
    uv run --with exchange_calendars,pandas,python-dateutil \\
        python tools/gen_xnys_calendar.py --desk-src ../../family-desk/backend/src

Both outputs are committed data, never generated in CI: the drift test compares them, which is the
point (a stale calendar and a hand edit both fail).
"""

from __future__ import annotations

import argparse
import datetime as dt
import importlib.util
import json
from datetime import date, timedelta
from pathlib import Path
from zoneinfo import ZoneInfo

import exchange_calendars as xcals

ET = ZoneInfo("America/New_York")
FIRST, LAST = date(2016, 1, 1), date(2030, 12, 31)
#: XNYS's first session on or after FIRST: the library's window starts at a session.
FIRST_SESSION = date(2016, 1, 4)
BRIDGE = Path(__file__).resolve().parent.parent
GENERATOR = "ai-trading/packages/market-data/bridge/tools/gen_xnys_calendar.py"


def load_desk_calendar(desk_src: Path):
    """The Desk's calendar module by file path: it has no package-relative imports."""
    path = desk_src / "ai_trading" / "core" / "calendar.py"
    spec = importlib.util.spec_from_file_location("_desk_calendar", path)
    if spec is None or spec.loader is None:
        raise SystemExit(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--desk-src", required=True, type=Path, help="packages/family-desk/backend/src")
    args = parser.parse_args()

    desk = load_desk_calendar(args.desk_src)
    cal = xcals.get_calendar("XNYS", start=FIRST_SESSION.isoformat(), end=LAST.isoformat())

    sessions: list[str] = []
    early: list[str] = []
    for label in cal.sessions_in_range(FIRST_SESSION.isoformat(), LAST.isoformat()):
        day = label.date()
        open_et = cal.session_open(label).tz_convert(ET)
        close_et = cal.session_close(label).tz_convert(ET)
        # The Go loader derives these two from rules; stop if the rules ever stop holding.
        assert (open_et.hour, open_et.minute) == (9, 30), (day, open_et)
        assert (close_et.hour, close_et.minute) in {(16, 0), (13, 0)}, (day, close_et)
        sessions.append(day.isoformat())
        if (close_et.hour, close_et.minute) == (13, 0):
            early.append(day.isoformat())

    embedded = {
        "note": (
            f"Generated by {GENERATOR} from exchange_calendars XNYS; do not hand-edit. Regenerate yearly "
            "(02u §9 ruling 6, sync-checklist item), then run `go test ./internal/xnys`: the Go loader derives "
            "each session's 09:30 ET open and 16:00 ET (13:00 ET on an early close) close from these dates plus "
            "tzdata, and testdata/calendar/xnys_python_golden.json holds the Desk calendar's instants."
        ),
        "source": f"exchange_calendars {xcals.__version__} XNYS",
        "generated": dt.date.today().isoformat(),
        "range": {"first": FIRST.isoformat(), "last": LAST.isoformat()},
        "sessions": sessions,
        "early_closes": early,
    }
    out = BRIDGE / "internal" / "xnys" / "xnys.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(embedded, separators=(",", ":")) + "\n")

    golden = {
        "source": "ai_trading.core.calendar.session('stock', day)",
        "generated_by": GENERATOR,
        "range": embedded["range"],
        "sessions": [],
    }
    day = FIRST
    while day <= LAST:
        found = desk.session("stock", day)
        if found is not None:
            golden["sessions"].append(
                {
                    "d": day.isoformat(),
                    "o": found.regular_open.strftime("%Y-%m-%dT%H:%M:%SZ"),
                    "c": found.regular_close.strftime("%Y-%m-%dT%H:%M:%SZ"),
                }
            )
        day += timedelta(days=1)
    if len(golden["sessions"]) != len(sessions):
        raise SystemExit(f"drift at generation: embedded {len(sessions)} sessions, Desk {len(golden['sessions'])}")
    gpath = BRIDGE / "testdata" / "calendar" / "xnys_python_golden.json"
    gpath.parent.mkdir(parents=True, exist_ok=True)
    gpath.write_text(json.dumps(golden, separators=(",", ":")) + "\n")

    print(f"{len(sessions)} sessions, {len(early)} early closes")
    print(f"{out} {out.stat().st_size} B")
    print(f"{gpath} {gpath.stat().st_size} B")


if __name__ == "__main__":
    main()